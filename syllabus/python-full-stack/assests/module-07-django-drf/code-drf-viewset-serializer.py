from rest_framework import viewsets, status
from rest_framework.decorators import action
from rest_framework.response import Response
from rest_framework.permissions import IsAuthenticated, AllowAny
from django_filters.rest_framework import DjangoFilterBackend
from rest_framework.filters import SearchFilter, OrderingFilter
from django.db.models import Avg, Count, Q


class StudentViewSet(viewsets.ModelViewSet):
    """
    CRUD API for Students at TechPath Institute.

    Endpoints (auto-generated by router):
      GET    /api/students/          — List all students (paginated)
      POST   /api/students/          — Create new student
      GET    /api/students/{id}/     — Get one student
      PUT    /api/students/{id}/     — Update student (full)
      PATCH  /api/students/{id}/     — Update student (partial)
      DELETE /api/students/{id}/     — Delete student

    Custom:
      GET    /api/students/stats/    — Aggregate stats
      GET    /api/students/toppers/  — Top 5 students
      POST   /api/students/bulk/     — Create multiple students
    """
    queryset = Student.objects.select_related("course").all()
    filter_backends = [DjangoFilterBackend, SearchFilter, OrderingFilter]
    filterset_fields = ["course", "city", "gender"]
    search_fields = ["name", "email"]
    ordering_fields = ["name", "marks", "enrolled_on"]
    ordering = ["-enrolled_on"]

    def get_serializer_class(self):
        """Use lightweight serializer for list, full for detail"""
        if self.action == "list":
            return StudentListSerializer
        return StudentDetailSerializer

    def get_permissions(self):
        """Allow anyone to list/retrieve, require auth for create/update/delete"""
        if self.action in ["list", "retrieve", "stats", "toppers"]:
            return [AllowAny()]
        return [IsAuthenticated()]

    @action(detail=False, methods=["get"])
    def stats(self, request):
        """GET /api/students/stats/ — Aggregate statistics"""
        total = Student.objects.count()
        avg = Student.objects.aggregate(avg=Avg("marks"))["avg"] or 0
        pass_count = Student.objects.filter(marks__gte=40).count()

        city_dist = dict(
            Student.objects
            .values_list("city")
            .annotate(count=Count("id"))
            .order_by("-count")
        )

        data = {
            "total_students": total,
            "average_marks": round(avg, 1),
            "pass_count": pass_count,
            "fail_count": total - pass_count,
            "city_distribution": city_dist,
        }
        return Response(data)

    @action(detail=False, methods=["get"])
    def toppers(self, request):
        """GET /api/students/toppers/ — Top 5 by marks"""
        toppers = self.get_queryset().filter(marks__gte=75).order_by("-marks")[:5]
        serializer = StudentListSerializer(toppers, many=True)
        return Response(serializer.data)

    @action(detail=False, methods=["post"])
    def bulk(self, request):
        """POST /api/students/bulk/ — Create multiple students at once"""
        serializer = StudentDetailSerializer(data=request.data, many=True)
        serializer.is_valid(raise_exception=True)
        serializer.save()
        return Response(
            {"created": len(serializer.data), "students": serializer.data},
            status=status.HTTP_201_CREATED,
        )


class CourseViewSet(viewsets.ModelViewSet):
    """
    CRUD API for Courses.

    Endpoints:
      GET    /api/courses/           — List all courses
      POST   /api/courses/           — Create course
      GET    /api/courses/{id}/      — Get course details
      PUT    /api/courses/{id}/      — Update course
      DELETE /api/courses/{id}/      — Delete course
    """
    queryset = Course.objects.annotate(student_count=Count("students"))
    serializer_class = CourseSerializer
    filter_backends = [SearchFilter, OrderingFilter]
    search_fields = ["name"]
    ordering_fields = ["name", "fee", "student_count"]
    ordering = ["name"]


