class CourseSerializer(serializers.ModelSerializer):
    """Serializer for Course model"""
    student_count = serializers.IntegerField(read_only=True)
    total_revenue = serializers.SerializerMethodField()

    class Meta:
        # model = Course
        fields = [
            "id", "name", "duration_months", "fee",
            "is_active", "student_count", "total_revenue",
            "created_at",
        ]

    def get_total_revenue(self, obj):
        """Calculate total revenue from enrolled students"""
        count = getattr(obj, "student_count", 0)
        return float(obj.fee * count) if count else 0


class StudentListSerializer(serializers.ModelSerializer):
    """Lightweight serializer for list view (fewer fields)"""
    course_name = serializers.CharField(source="course.name", read_only=True)

    class Meta:
        # model = Student
        fields = ["id", "name", "email", "city", "course_name", "marks"]


class StudentDetailSerializer(serializers.ModelSerializer):
    """Full serializer for detail/create/update"""
    course_name = serializers.CharField(source="course.name", read_only=True)
    status = serializers.CharField(read_only=True)

    class Meta:
        # model = Student
        fields = [
            "id", "name", "email", "phone", "city", "gender",
            "course", "course_name", "marks", "status", "enrolled_on",
        ]
        read_only_fields = ["enrolled_on"]

    def validate_marks(self, value):
        if value < 0 or value > 100:
            raise serializers.ValidationError("Marks must be between 0 and 100")
        return value

    def validate_email(self, value):
        """Ensure email is unique (case-insensitive)"""
        value = value.lower().strip()
        qs = Student.objects.filter(email__iexact=value)
        if self.instance:
            qs = qs.exclude(pk=self.instance.pk)
        if qs.exists():
            raise serializers.ValidationError("A student with this email already exists.")
        return value


class StudentStatsSerializer(serializers.Serializer):
    """Serializer for stats endpoint (no model)"""
    total_students = serializers.IntegerField()
    average_marks = serializers.FloatField()
    pass_count = serializers.IntegerField()
    fail_count = serializers.IntegerField()
    city_distribution = serializers.DictField()


